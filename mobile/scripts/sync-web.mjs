// Copies the citizen website (../frontend) into the app's web bundle (www/).
//
// The app runs the exact same pages, CSS, and motions as the website; only
// config.js differs — it points at the backend server and sets isApp, which
// swaps "Install App" for "Share App" and hides every install prompt.
//
// Server address: PLANETWATCH_SERVER_URL, else the first CLI argument, else
// http://<this computer's LAN IP>:5000.
import { cpSync, existsSync, rmSync, writeFileSync } from 'node:fs';
import { networkInterfaces } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const mobileDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const frontendDir = join(mobileDir, '..', 'frontend');
const wwwDir = join(mobileDir, 'www');

function lanIp() {
  for (const addresses of Object.values(networkInterfaces())) {
    for (const address of addresses || []) {
      if (address.family === 'IPv4' && !address.internal && !address.address.startsWith('169.254.')) {
        return address.address;
      }
    }
  }
  return 'localhost';
}

const serverUrl = (process.env.PLANETWATCH_SERVER_URL || process.argv[2] || `http://${lanIp()}:5000`).replace(/\/$/, '');

if (existsSync(wwwDir)) rmSync(wwwDir, { recursive: true, force: true });
cpSync(frontendDir, wwwDir, { recursive: true });

// The app never shows installation info — these pages only exist on the website.
for (const page of ['install.html', 'get-app.html', 'js/pages/install.js', 'manifest.webmanifest']) {
  rmSync(join(wwwDir, page), { force: true });
}

writeFileSync(
  join(wwwDir, 'js', 'config.js'),
  `// Generated by mobile/scripts/sync-web.mjs — edit frontend/js/config.js for the website.
window.PW_CONFIG = {
  apiBase: ${JSON.stringify(serverUrl)},
  isApp: true,
};
`,
);

console.log(`Bundled frontend/ into mobile/www — app will talk to ${serverUrl}`);
